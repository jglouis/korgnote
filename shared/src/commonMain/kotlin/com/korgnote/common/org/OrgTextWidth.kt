package com.korgnote.common.org

/**
 * How many columns [text] takes once Emacs displays it in an Org buffer, as `org-string-width`
 * measures it to align a table: a bracket link shows only its description — or, without one, what it
 * points to — and a character takes the columns Emacs gives it (see [charWidth]).
 */
fun orgDisplayWidth(text: String): Int {
    val shown = if ("[[" in text) bracketLink.replace(text) { it.groupValues[2].ifEmpty { it.groupValues[1] } } else text
    var width = 0
    var i = 0
    while (i < shown.length) {
        val high = shown[i]
        val codePoint = if (high.isHighSurrogate() && i + 1 < shown.length && shown[i + 1].isLowSurrogate()) {
            i++
            ((high.code - 0xD800) shl 10) + (shown[i].code - 0xDC00) + 0x10000
        } else {
            high.code
        }
        width += charWidth(codePoint)
        i++
    }
    return width
}

private val bracketLink = Regex("""\[\[((?:[^\[\]\\]|\\.)+)](?:\[(.+?)])?]""")

/**
 * The columns Emacs gives [codePoint] (its `char-width-table`): none for a combining mark or a
 * variation selector, two for East Asian wide and full-width characters and most emoji, one for the
 * rest.
 */
internal fun charWidth(codePoint: Int): Int = when {
    ZERO_WIDTH.any { codePoint in it } -> 0
    WIDE.any { codePoint in it } -> 2
    else -> 1
}

